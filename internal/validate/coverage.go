package validate

import (
	"fmt"
	"strings"

	"github.com/maskedsyntax/golings/internal/catalog"
)

// CoverageMarkdown renders docs/curriculum-coverage.md: every Go by Example
// topic, the exercises that cover it, and whether it meets the minimum.
func CoverageMarkdown(cat *catalog.Catalog) string {
	byTopic := map[string][]string{}
	for _, ex := range cat.Exercises() {
		byTopic[ex.Topic] = append(byTopic[ex.Topic], ex.ID)
	}
	covered := 0
	for _, t := range cat.Topics.Topics {
		if len(byTopic[t.ID]) >= MinExercisesPerTopic {
			covered++
		}
	}

	var b strings.Builder
	b.WriteString("# Curriculum coverage\n\n")
	b.WriteString("<!-- Generated by `go run ./cmd/golings-dev coverage --write`. Do not edit by hand. -->\n\n")
	fmt.Fprintf(&b, "- Curriculum version: %s\n", cat.Version())
	fmt.Fprintf(&b, "- Topic inventory: %s, snapshot %s (%d topics)\n", cat.Topics.Source, cat.Topics.SnapshotDate, len(cat.Topics.Topics))
	fmt.Fprintf(&b, "- Exercises: %d\n", len(cat.Exercises()))
	fmt.Fprintf(&b, "- Topics with at least %d exercises: %d/%d\n", MinExercisesPerTopic, covered, len(cat.Topics.Topics))

	module := ""
	for _, t := range cat.Topics.Topics {
		if t.Module != module {
			module = t.Module
			fmt.Fprintf(&b, "\n## %s — %s\n\n", module[:2], cat.ModuleTitle(module))
			b.WriteString("| # | Topic | Exercises | Status |\n|---|---|---|---|\n")
		}
		ids := byTopic[t.ID]
		status := "✅"
		switch {
		case len(ids) == 0:
			status = "⬜ none"
		case len(ids) < MinExercisesPerTopic:
			status = fmt.Sprintf("🟨 %d/%d", len(ids), MinExercisesPerTopic)
		}
		list := "—"
		if len(ids) > 0 {
			list = "`" + strings.Join(ids, "`, `") + "`"
		}
		fmt.Fprintf(&b, "| %03d | [%s](%s) | %s | %s |\n", t.SourceOrdinal, t.Title, t.URL, list, status)
	}
	return b.String()
}
