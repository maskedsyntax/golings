// switch_02: A switch with no expression (reference solution)
package fizzbuzz

import "strconv"

// FizzBuzz returns the FizzBuzz word for n.
func FizzBuzz(n int) string {
	switch {
	case n%15 == 0:
		return "FizzBuzz"
	case n%3 == 0:
		return "Fizz"
	case n%5 == 0:
		return "Buzz"
	default:
		return strconv.Itoa(n)
	}
}
