// worker_pools_04: Fan-in (reference solution)
package merge

import "sync"

// Merge copies every value from every input to the returned channel and
// closes it once all inputs are closed.
func Merge(chans ...<-chan int) <-chan int {
	out := make(chan int)
	var wg sync.WaitGroup
	for _, c := range chans {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for v := range c {
				out <- v
			}
		}()
	}
	go func() {
		wg.Wait()
		close(out)
	}()
	return out
}
